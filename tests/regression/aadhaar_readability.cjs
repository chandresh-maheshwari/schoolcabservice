const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require.resolve('../../public/js/driver-document-ocr.js'), 'utf8');
const context = {DriverDocumentParser: require('../../public/js/driver-document-parser.js')};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('    function readableAadhaarValue('), source.indexOf('    function init(panel)')), context);
const readable = context.readableAadhaarValue;
const clear = {text: 'TEST PERSON DOB 01/01/2010 MALE 2345 6789 0123', confidence: 95};
assert.equal(readable('TEST PERSON', [clear, clear]), true);
assert.equal(readable('2345 6789 0123', [clear, clear]), true);
assert.equal(readable('TEST PERSON', [clear]), false, 'One guessed pass is insufficient');
assert.equal(readable('TEST PERSON', [{...clear, confidence: 60}, {...clear, confidence: 60}]), false);
assert.equal(readable('TEST PERSON', [clear, {text: 'BEST PERSON', confidence: 95}]), false);
const word = (text, confidence) => ['5', '1', '1', '1', '1', '1', '0', '0', '20', '20', String(confidence), text].join('\t');
const unclearName = {...clear, tsv: 'header\n' + word('TEST', 30) + '\n' + word('PERSON', 95)};
assert.equal(readable('TEST PERSON', [unclearName, unclearName]), false, 'Overall confidence must not hide blurred words');
assert.equal(readable('Pali', [clear, clear]), false, 'Inferred or absent values must not auto-fill');
const nameReading = name => ({text: `Government of India\n${name}\nDOB: 01/01/2010\nFEMALE\n2345 6789 0123`, confidence: 95});
const cleanName = nameReading('Patel Poojaben Vinodbhai');
const noisyName = nameReading('Patel Poojaben Vinodbhai EF');
assert.equal(context.reliableAadhaarName([cleanName, cleanName, noisyName]), 'Patel Poojaben Vinodbhai');
assert.equal(context.reliableAadhaarName([cleanName, noisyName]), '', 'Conflicting full names must not be accepted through prefix agreement');
const initialName = nameReading('Patel Poojaben Vinodbhai K');
assert.equal(context.reliableAadhaarName([initialName, initialName]), 'Patel Poojaben Vinodbhai K', 'Printed initials must not be stripped');
assert.equal(context.reliableAadhaarName([cleanName, cleanName, noisyName, noisyName]), '', 'Equal support for conflicting names must fail closed');
console.log('Clear repeated text accepted; low-confidence, conflicting and inferred values rejected');
